import pytest

from model_runtime.backends.ko_numbers import native, normalize, sino


@pytest.mark.parametrize(
    ("text", "spoken"),
    [
        ("260조 원이래", "이백육십조 원이래"),
        ("1조 5000억", "일조 오천억"),
        ("1,234,000원", "백이십삼만사천원"),
        ("10만 원", "십만 원"),
        ("2.5% 올랐어", "이 점 오 퍼센트 올랐어"),
        ("3명이 왔어", "세 명이 왔어"),
        ("20살이야", "스무 살이야"),
        ("오후 3시 15분", "오후 세 시 십오분"),
        ("11번째", "열한 번째"),
        ("2개월 뒤", "이개월 뒤"),
        ("20대 청년", "이십대 청년"),
        ("2026년 6월 10일", "이천이십육년 유월 십일"),
        ("10월", "시월"),
        ("$5", "오 달러"),
        ("010", "공일공"),
        ("숫자 없음", "숫자 없음"),
        ("10:30에 만나", "열 시 삼십 분에 만나"),
        ("12:00까지", "열두 시까지"),
        ("0:05", "영 시 오 분"),
        ("3:2로 이겼어", "삼 대 이로 이겼어"),
        ("3~4명이 왔어", "서너 명이 왔어"),
        ("1~2시간", "한두 시간"),
        ("2~3번째", "두세 번째"),
        ("5~10명", "다섯에서 열 명"),
        ("10~20% 올라", "십에서 이십 퍼센트 올라"),
        ("$5~$10", "오 달러에서 십 달러"),
        ("1번째 줄", "첫 번째 줄"),
        ("1/2만 먹어", "이분의 일만 먹어"),
        ("3/4", "사분의 삼"),
        ("5/3", "오/삼"),
        ("010-1234-5678로 전화해", "공일공 일이삼사 오육칠팔로 전화해"),
        ("5ml", "오 밀리리터"),
    ],
)
def test_대사의_숫자를_한글_읽기로_바꾼다(text: str, spoken: str) -> None:
    assert normalize(text) == spoken


def test_한자어와_고유어_읽기() -> None:
    assert sino(0) == "영"
    assert sino(10) == "십"
    assert sino(10000) == "만"
    assert sino(100_000_000) == "억"
    assert sino(21_0000_0005) == "이십일억오"
    assert native(1) == "한"
    assert native(99) == "아흔아홉"
